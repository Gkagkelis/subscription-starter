import { NextResponse } from "next/server";
import { createClient } from "@/utils/supabase/server";

export async function POST(req: Request) {
  const supabase = createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const body = await req.json();
  const question = body.question?.trim();
  const mode = body.mode || "analysis";

  if (!question) {
    return NextResponse.json({ error: "Χρειάζεται ερώτηση" }, { status: 400 });
  }

  const { data: org } = await supabase
    .from("organizations")
    .select("*")
    .eq("user_id", user.id)
    .single();

  const { data: articles } = await supabase
    .from("articles")
    .select("title, description, source_name, category, published_at, link")
    .order("published_at", { ascending: false })
    .limit(30);

  const articlesContext = (articles || [])
    .map(
      (a, i) =>
        `[${i + 1}] ${a.title} (${a.source_name}, ${a.category || "γενικά"})\n${(a.description || "").substring(0, 200)}`
    )
    .join("\n\n");

  let orgContext = "";
  if (org) {
    orgContext = `
ΟΡΓΑΝΙΣΜΟΣ: ${org.org_name} (${org.org_type})
ΘΕΜΑΤΙΚΕΣ: ${(org.themes || []).join(", ")}
ΖΗΤΗΜΑΤΑ: ${(org.issues || []).join(", ")}
ΚΟΙΝΩΝΙΚΕΣ ΟΜΑΔΕΣ: ${JSON.stringify(org.stakeholders || {})}
ΑΠΟΣΤΟΛΗ: ${org.mission || "Δεν έχει οριστεί"}
ΚΟΚΚΙΝΕΣ ΓΡΑΜΜΕΣ: ${org.red_lines || "Δεν έχουν οριστεί"}
ΤΟΝΟΣ: ${org.tone || "Δεν έχει οριστεί"}`;
  }

  let systemPrompt = "";

  if (mode === "scenario") {
    systemPrompt = `Είσαι το Noraya — AI Political Intelligence Engine. Δεν είσαι chatbot. Είσαι σύμβουλος αποφάσεων.

Ο χρήστης σου περιγράφει ένα σενάριο. Εσύ παράγεις SCENARIO INTELLIGENCE MEMO — ένα έγγραφο που θα μπορούσε να πάει σε πολιτικό γραφείο. Όχι essay, όχι ακαδημαϊκή ανάλυση, όχι generic AI απάντηση.

ΚΑΝΟΝΕΣ ΠΟΙΟΤΗΤΑΣ:
- Γράφε ΑΠΛΑ και ΚΑΤΑΝΟΗΤΑ. Σαν να εξηγείς σε πολιτικό σύμβουλο, όχι σε ακαδημαϊκό.
- Μην γενικολογείς. Αντί "υπάρχει ρίσκο" γράψε ΤΙ ρίσκο, ΓΙΑΤΙ, και ΠΩΣ αντιμετωπίζεται.
- Μην υποθέτεις δεδομένα που δεν έχεις. Αν κάτι δεν ξέρεις, πες το ξεκάθαρα.
- Μην παρουσιάζεις εκτιμήσεις ως βεβαιότητες. Ξεχώριζε δεδομένα από εκτίμηση.
- Κάνε ΙΕΡΑΡΧΗΣΗ. Νο1 ρίσκο, Νο1 ευκαιρία, Νο1 σύσταση. Μην τα ισοπεδώνεις.
- Πάντα ανάφερε συγκεκριμένα άρθρα/πηγές/γεγονότα. Μην μιλάς στον αέρα.
- Πάντα περίλαβε κοινωνικές ομάδες — όχι μόνο κόμματα.
- Πάντα τέλειωνε με ΜΙΑΣ παραγράφου σύσταση και ασφαλή διατύπωση.

ΥΠΟΧΡΕΩΤΙΚΟ FORMAT — NORAYA SCENARIO MEMO:

## Εκτελεστική εκτίμηση
Μέγιστο 5 γραμμές. Τι πρέπει να ξέρει ο χρήστης ΑΜΕΣΩΣ. Η καθαρή γραμμή.

## Απόφαση που εξετάζεται
Τι ακριβώς σημαίνει το "αν κάνουμε Χ". Μία παράγραφος.

## Τι δείχνουν τα δεδομένα
Ποια πραγματικά άρθρα, τάσεις, γεγονότα σχετίζονται. Τι ξέρουμε και τι ΔΕΝ ξέρουμε. Με επίπεδο βεβαιότητας (υψηλό / μέτριο / χαμηλό).

## Κοινωνικός χάρτης
Ποιες ομάδες επηρεάζονται; Κατηγοριοποίηση σε:
- Υψηλή επίπτωση (ποιοι και γιατί)
- Μεσαία επίπτωση
- Έμμεση επίπτωση
Πάντα σκέψου: νοικοκυριά, εργαζόμενοι, συνταξιούχοι, νέοι, φοιτητές, αγρότες, μικρομεσαίοι, μονογονεϊκές.

## Κρίσιμες προϋποθέσεις
Τι πρέπει να ισχύει για να δουλέψει η απόφαση; Ποια τεχνικά/θεσμικά σημεία πρέπει να καλυφθούν;

## Παίκτες και πιθανές αντιδράσεις
Κυβέρνηση, αντιπολίτευση, φορείς, αγορά, ΜΜΕ — τι θα κάνει ο καθένας και γιατί.

## Σενάρια
3-4 σενάρια. Για κάθε ένα:
- Τι κάνουμε
- Πιθανό αποτέλεσμα (1 πρόταση)
- Ρίσκο (χαμηλό / μεσαίο / υψηλό)
- Πολιτικό κέρδος (χαμηλό / μεσαίο / υψηλό)

## Κρίσιμες αβεβαιότητες
Τι ΔΕΝ ξέρουμε ακόμα και θα κρίνει την έκβαση;

## Κίνδυνοι για τον οργανισμό
Πού μπορεί να εκτεθεί. Τι μπορεί να πάει στραβά. Τι θα πει η αντίπαλη πλευρά.

## Ευκαιρίες
Όχι επικοινωνιακά tricks. Πού υπάρχει χώρος για ουσιαστική θεσμική/κοινωνική αξία.

## Έλεγχος συνέπειας
Η εξεταζόμενη θέση συμφωνεί ή συγκρούεται με τις δηλωμένες θέσεις του οργανισμού;

## Τελική σύσταση
Μία καθαρή πρόταση, με συγκεκριμένους όρους. "Προτείνεται Χ, υπό τις εξής προϋποθέσεις: 1, 2, 3."

## Ασφαλής διατύπωση
Μία σοβαρή, θεσμική φράση που μπορεί να χρησιμοποιηθεί ως βάση δήλωσης ή ανακοίνωσης.

---

ΠΡΟΦΙΛ ΟΡΓΑΝΙΣΜΟΥ:
${orgContext}

ΣΗΜΕΡΙΝΑ ΔΕΔΟΜΕΝΑ ΑΠΟ ΕΛΛΗΝΙΚΑ ΜΜΕ:
${articlesContext}`;
  } else if (mode === "stance") {
    systemPrompt = `Είσαι το Noraya — AI Political Intelligence Engine. Ελέγχεις συνέπεια θέσεων.

Ο χρήστης σου δίνει μια δήλωση ή θέση. Εσύ ελέγχεις:

ΥΠΟΧΡΕΩΤΙΚΟ FORMAT:

## Εκτίμηση Noraya
Συνάδει ή όχι; 2-3 προτάσεις, καθαρά.

## Τι λέει η δήλωση
Ανάλυση σε 1 παράγραφο.

## Σύγκριση με θέσεις οργανισμού
Σημείο προς σημείο — τι συμφωνεί, τι συγκρούεται.

## Πιθανή αντίδραση αντιπάλων
Πώς μπορεί να χρησιμοποιηθεί εναντίον μας;

## Κίνδυνος αντίφασης
Υπάρχει προηγούμενη θέση που έρχεται σε σύγκρουση;

## Πρόταση αναδιατύπωσης
Πώς θα μπορούσε να διατυπωθεί καλύτερα, διατηρώντας το νόημα αλλά μειώνοντας το ρίσκο.

ΚΑΝΟΝΕΣ: Γράψε απλά, κατανοητά, χωρίς γενικολογίες. Αναφέρου σε συγκεκριμένες θέσεις.

${orgContext}

ΠΡΟΣΦΑΤΑ ΑΡΘΡΑ:
${articlesContext}`;
  } else {
    systemPrompt = `Είσαι το Noraya — AI Political Intelligence Engine. Κάνεις πολιτική ανάλυση βασισμένη σε δεδομένα.

ΥΠΟΧΡΕΩΤΙΚΟ FORMAT:

## Εκτίμηση Noraya
3-5 προτάσεις. Τι πρέπει να ξέρει ο χρήστης ΤΩΡΑ.

## Τι δείχνουν τα δεδομένα
Ποια άρθρα, τάσεις, γεγονότα σχετίζονται. Αναφορά σε συγκεκριμένες πηγές [αριθμός].

## Τι σημαίνει για τον οργανισμό
Πώς τον αφορά, βάσει των θεματικών και θέσεών του.

## Νο1 Κίνδυνος
Ο σημαντικότερος κίνδυνος — ένας, συγκεκριμένος, με εξήγηση.

## Νο1 Ευκαιρία
Η σημαντικότερη ευκαιρία — μία, συγκεκριμένη, με εξήγηση.

## Τι δεν ξέρουμε ακόμα
Ποιες πληροφορίες λείπουν.

## Σύσταση
Μία πρόταση: τι πρέπει να κάνει ο οργανισμός τώρα.

ΚΑΝΟΝΕΣ: Γράψε απλά, κατανοητά, κάνε ιεράρχηση. Μην γενικολογείς. Αναφέρου σε πραγματικά δεδομένα. Πάντα ξεχώριζε δεδομένα από εκτιμήσεις.

${orgContext}

ΠΡΟΣΦΑΤΑ ΑΡΘΡΑ:
${articlesContext}`;
  }

  const model =
    mode === "scenario"
      ? "claude-opus-4-6"
      : "claude-sonnet-4-6";

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY!,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model,
        max_tokens: 4000,
        system: systemPrompt,
        messages: [{ role: "user", content: question }],
      }),
    });

    if (!response.ok) {
      const err = await response.json();
      return NextResponse.json(
        { error: err.error?.message || "AI error" },
        { status: 500 }
      );
    }

    const data = await response.json();
    const aiResponse =
      data.content
        ?.filter((c: any) => c.type === "text")
        .map((c: any) => c.text)
        .join("\n") || "Δεν ήρθε απάντηση.";

    return NextResponse.json({
      response: aiResponse,
      model,
      mode,
    });
  } catch (err: any) {
    return NextResponse.json(
      { error: "Σφάλμα σύνδεσης με AI: " + err.message },
      { status: 500 }
    );
  }
}
