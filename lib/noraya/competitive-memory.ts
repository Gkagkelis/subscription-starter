// Σύντομη γενική ανάγνωση του πεδίου (διαρθρωτική, όχι αριθμητική)
export const FIELD_OVERVIEW =
  "Το σύστημα είναι σε ΠΟΛΥΚΕΝΤΡΙΚΗ αναδιάταξη (όχι απλός διπολισμός). Τέσσερα ταμπλό: (1) Εξουσία: ΝΔ vs ΕΛΑΣ. (2) Ηθική αντιπολίτευση: κυρίως Καρυστιανού (πίεση σε Πλεύση/ΕΛΑΣ/ΝΔ). (3) Κεντροαριστερή ηγεμονία: ΕΛΑΣ vs ΠΑΣΟΚ vs ΣΥΡΙΖΑ/Νέα Αριστερά/ΜέΡΑ25/Πλεύση. (4) Δεξιά πίεση: ΝΔ vs Ελληνική Λύση/Φωνή Λογικής/Νίκη/πιθανός Σαμαράς. Το διακύβευμα: ποιος θα ελέγξει τον ορισμό της «αλλαγής».";

function normGr(s: string): string {
  return (s || "").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
}

// Βρες την εγγραφή ενός κόμματος (με βάση όνομα/alias)
export function findParty(input: string): PartyStructural | null {
  const n = normGr(input);
  if (!n) return null;
  for (const p of PARTY_STRUCTURAL) {
    if (normGr(p.name).includes(n) || n.includes(p.key) || p.aliases.some((a) => n.includes(normGr(a)))) {
      return p;
    }
  }
  return null;
}

function fmt(p: PartyStructural): string {
  return [
    `■ ${p.name}`,
    `  Brand: ${p.brand}`,
    `  Άμεσοι αντίπαλοι (δομικά): ${p.rivals}`,
    `  Δεξαμενές: ${p.pools}`,
    `  Παγίδα: ${p.trap}`,
  ].join("\n");
}

// Δομικό πλαίσιο ανταγωνισμού για το ΕΠΙΛΕΓΜΕΝΟ κόμμα + τους άμεσους αντιπάλους του.
export function buildCompetitiveContext(partyInput: string): string {
  const me = findParty(partyInput);
  const lines: string[] = ["ΔΟΜΙΚΟ ΠΛΑΙΣΙΟ ΑΝΤΑΓΩΝΙΣΜΟΥ (διαρθρωτικό — ΟΧΙ τρέχοντα ποσοστά):", FIELD_OVERVIEW, ""];
  if (me) {
    lines.push("ΤΟ ΚΟΜΜΑ ΣΟΥ:");
    lines.push(fmt(me));
    // Πρόσθεσε τους αντιπάλους που αναφέρονται στη γραμμή rivals (ταίριασμα με aliases + όρια λέξης)
    const mentions = (text: string, term: string): boolean => {
      const t = normGr(text);
      const w = normGr(term);
      if (!w) return false;
      if (w.length <= 3) return new RegExp(`(^|[^a-z\\u03b1-\\u03c9])${w}([^a-z\\u03b1-\\u03c9]|$)`).test(t);
      return t.includes(w);
    };
    const others = PARTY_STRUCTURAL.filter(
      (pp) => pp.key !== me.key && (pp.aliases.some((a) => mentions(me.rivals, a)) || mentions(me.rivals, pp.name.split(" ")[0]))
    );
    if (others.length) {
      lines.push("", "ΑΜΕΣΟΙ ΑΝΤΙΠΑΛΟΙ (δομικά προφίλ):");
      for (const o of others.slice(0, 4)) lines.push(fmt(o));
    }
  } else {
    // Άγνωστο κόμμα → δώσε όλη τη συνοπτική εικόνα
    lines.push("ΟΛΑ ΤΑ ΣΧΗΜΑΤΑ (σύντομα):");
    for (const p of PARTY_STRUCTURAL) lines.push(fmt(p));
  }
  lines.push(
    "",
    "ΟΔΗΓΙΑ: Αυτά είναι ΔΙΑΡΘΡΩΤΙΚΑ μοτίβα που αλλάζουν αργά. Τα ΠΟΣΟΣΤΑ και η ΤΡΕΧΟΥΣΑ ΔΥΝΑΜΙΚΗ έρχονται ΜΟΝΟ από web_search (dimoskopiseis.gr/πρακτορεία). Αν το web_search δείξει κάτι που αντιφάσκει με τα παραπάνω, ΠΡΟΤΙΜΗΣΕ το ζωντανό και πες ρητά ότι το τοπίο μετακινείται."
  );
  return lines.join("\n");
}
